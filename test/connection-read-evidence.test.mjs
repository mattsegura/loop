import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { ConnectionPool } from '../lib/mcp-client.mjs';
import { Vault } from '../lib/vault.mjs';
import { connectionReadiness } from '../lib/connection-readiness.mjs';

test('only a successful provider-reported read establishes evidence for the current connection', async (t) => {
  const dir = await mkdtemp(path.join(tmpdir(), 'loop-observed-read-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const vault = new Vault(dir);
  const conn = { id: 'sample', name: 'Sample', accountLabel: 'Work', url: 'https://example.test/mcp', transport: 'http', enabled: true,
    tools: [{ name: 'read_sample', annotations: { readOnlyHint: true } }, { name: 'change_sample' }] };
  const pool = new ConnectionPool({ get: async () => conn }, vault);
  const read = () => pool.callTool(conn.id, 'read_sample');
  const good = () => ({ content: [{ type: 'text', text: 'private provider data' }] });
  pool._dispatchTool = async () => good();
  assert.equal(connectionReadiness(conn).ready, true);
  assert.equal(pool.readEvidence(conn), null);
  await pool.callTool(conn.id, 'change_sample');
  assert.equal(pool.readEvidence(conn), null);
  await read();
  const proof = pool.readEvidence(conn);
  assert.equal(proof.connectionId, 'sample');
  assert.equal(proof.tool, 'read_sample');
  assert.ok(Number.isFinite(Date.parse(proof.succeededAt)));
  assert.equal(JSON.stringify(proof).includes('private provider data'), false);
  assert.equal(pool.readEvidence({ ...conn, id: 'other' }), null);
  pool._dispatchTool = async () => ({ content: [{ type: 'text', text: '{"ok":false}' }] });
  await read();
  assert.equal(pool.readEvidence(conn), null);
  pool._dispatchTool = async () => good();
  await read();

  await vault.set('FIXTURE', 'synthetic-key', 'fixture');
  assert.equal(pool.readEvidence(conn), null);
  await read();
  conn.accountLabel = 'Another account';
  assert.equal(pool.readEvidence(conn), null);
  await read();
  conn.authRequired = true;
  assert.equal(pool.readEvidence(conn), null);
  conn.authRequired = false;
  assert.equal(pool.readEvidence(conn), null);
  await read();
  let finishOldRead;
  let started;
  const running = new Promise((resolve) => { started = resolve; });
  pool._dispatchTool = () => new Promise((resolve) => { finishOldRead = resolve; started(); });
  const older = read();
  await running;
  pool._dispatchTool = async () => ({ content: [], isError: true });
  await read();
  finishOldRead(good());
  await older;
  assert.equal(pool.readEvidence(conn), null);
  pool._dispatchTool = async () => good();
  await read();
  pool._dispatchTool = async () => { throw new Error('Synthetic sign-in failure'); };
  await assert.rejects(read(), /Synthetic/);
  assert.equal(pool.readEvidence(conn), null);
});
